-- ---------------------------------------------------------------------
-- STEP 0  確認（何も変えない）
--   products.category に入っている名前が、下の10種類と同じかを見る
--   10行出て、名前が STEP 1 の10種類と同じならOK
-- ---------------------------------------------------------------------
SELECT category, COUNT(*) AS 件数
FROM products
GROUP BY category
ORDER BY category;


-- ---------------------------------------------------------------------
-- STEP 1  categories（カテゴリーの一覧）を作る
-- ---------------------------------------------------------------------
