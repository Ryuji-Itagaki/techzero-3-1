-- ---------------------------------------------------------------------
-- STEP 5  商品ごとのタグを入れるテーブル（2つ）
--   product_id は products と同じ varchar(10)・utf8mb4_ja_0900_as_cs にそろえてある
--   （型や照合順序がずれると外部キーが作れないため）
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS product_taste_groups (
  product_id VARCHAR(10) NOT NULL,
  group_id   VARCHAR(10) NOT NULL,
  PRIMARY KEY (product_id, group_id),
  CONSTRAINT fk_ptg_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT fk_ptg_group   FOREIGN KEY (group_id)   REFERENCES taste_groups (group_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_ja_0900_as_cs;

CREATE TABLE IF NOT EXISTS product_tastes (
  product_id VARCHAR(10) NOT NULL,
  taste_id   VARCHAR(10) NOT NULL,
  PRIMARY KEY (product_id, taste_id),
  CONSTRAINT fk_pt_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT fk_pt_taste   FOREIGN KEY (taste_id)   REFERENCES tastes (taste_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_ja_0900_as_cs;


-- ---------------------------------------------------------------------
-- STEP 6  確認
--   categories 10 / taste_groups 13 / tastes 101 になっていればOK
-- ---------------------------------------------------------------------
SELECT 'categories' AS t, COUNT(*) FROM categories
UNION ALL SELECT 'taste_groups', COUNT(*) FROM taste_groups
UNION ALL SELECT 'tastes', COUNT(*) FROM tastes
UNION ALL SELECT 'product_taste_groups', COUNT(*) FROM product_taste_groups
UNION ALL SELECT 'product_tastes', COUNT(*) FROM product_tastes;

