-- ---------------------------------------------------------------------
-- STEP 2  products に category_id を足して、埋める
--   ※ ALTER TABLE ... ADD COLUMN は1回だけ実行する（2回目はエラーになる）
-- ---------------------------------------------------------------------
ALTER TABLE products
  ADD COLUMN category_id VARCHAR(10) NULL AFTER product_name;

UPDATE products p
JOIN categories c ON c.category_name = p.category
SET p.category_id = c.category_id
WHERE p.product_id IS NOT NULL;

-- 埋まらなかった商品を確認する。0件ならOK。1件以上なら STEP 2b に進まず、結果を見せてください
SELECT product_id, category
FROM products
WHERE category_id IS NULL;

-- STEP 2b  0件だったら、「必ずある」（NOT NULL）にして categories につなぐ
ALTER TABLE products
  MODIFY category_id VARCHAR(10) NOT NULL,
  ADD CONSTRAINT fk_products_category
    FOREIGN KEY (category_id) REFERENCES categories (category_id);


